// Run after editing chapter pages or the edition records: node rebuild-search.cjs
const fs = require('node:fs');
const vm = require('node:vm');
const labels = {index:'首页 · 小纸片的书馆书签',about:'博主档案 · 活动足迹',characters:'角色世界 · 付丧神双子',editions:'衣装档案',works:'作品与幕后 · 制作署名',gifts:'周边手记 · 纪念回馈',start:'入坑指南 · 读书与陪伴',sources:'参考资料 · 关于本站'};
const strip = s => s.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
const data = Object.entries(labels).map(([id,title]) => ({title,url:id+'.html',text:strip(fs.readFileSync(id+'.html','utf8').match(/<main>([\s\S]*?)<\/main>/)[1])}));
const sandbox = {document:{getElementById:()=>null,querySelectorAll:()=>[]},location:{pathname:'/editions.html',search:''},window:{addEventListener:()=>{}},URLSearchParams};
const editions = vm.runInNewContext(fs.readFileSync('app.js','utf8')+'\neditions',sandbox);
for (const e of editions) data.push({title:e.name+' · 衣装档案',url:'editions.html?look='+encodeURIComponent(e.name),text:e.label+' '+e.desc+' '+e.note});
fs.writeFileSync('search-data.js','// Generated by node rebuild-search.cjs.\nwindow.fanSearchData = '+JSON.stringify(data,null,2)+';\n');
console.log(`Indexed ${data.length} archive records.`);
